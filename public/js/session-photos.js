(() => {
	"use strict";

	const MAX_PHOTOS = 4;
	const MUTATION_CONTROLS = [
		".photo-upload-input",
		".photo-upload-submit",
		".photo-delete-start",
		".photo-delete-confirm",
		".photo-delete-cancel",
	].join(",");

	function enhancePhotoInputs(root = document) {
		for (const input of root.querySelectorAll?.(".photo-upload-input") || []) {
			input.multiple = true;
		}
	}

	function isMutationBusy(source) {
		return (
			source.closest(".session-photos-content")?.dataset.photoBusy === "true"
		);
	}

	function setMutationBusy(source, busy) {
		const content = source.closest(".session-photos-content");
		if (!content) return;
		if (busy) {
			content.dataset.photoBusy = "true";
		} else {
			delete content.dataset.photoBusy;
		}
		for (const control of content.querySelectorAll(MUTATION_CONTROLS)) {
			if (busy) {
				control.dataset.photoDisabledBefore = String(control.disabled);
				control.disabled = true;
			} else {
				control.disabled = control.dataset.photoDisabledBefore === "true";
				delete control.dataset.photoDisabledBefore;
			}
		}
	}

	function statusElement(source) {
		return source
			.closest(".session-photos-content")
			?.querySelector(".photo-upload-status");
	}

	function setStatus(source, message, isError = false) {
		const status = statusElement(source);
		if (!status) return;
		status.textContent = message;
		status.dataset.state = isError ? "error" : "info";
	}

	async function responseError(response) {
		let error = "";
		try {
			error = (await response.json()).error || "";
		} catch (_error) {
			// The status code still provides a useful fallback message.
		}

		if (error === "unsupported_type") {
			return "JPEG、PNG、WebP形式の写真を選択してください。";
		}
		if (error === "too_large") {
			return "写真は1枚10 MiB以下にしてください。";
		}
		if (error === "limit_exceeded") {
			return "写真は1セッションにつき4枚までです。";
		}
		if (response.status === 401 && error === "access_not_configured") {
			return "アップロード認証が設定されていません。管理者に確認してください。";
		}
		if (response.status === 401) {
			return "認証に失敗しました。ページを再読み込みしてお試しください。";
		}
		if (response.status === 403) {
			return "この操作は許可されていません。ページを再読み込みしてお試しください。";
		}
		if (response.status === 404) {
			return "写真またはセッションが見つかりません。";
		}
		return "処理に失敗しました。時間をおいて再度お試しください。";
	}

	function restoreFocus(target, focusTarget) {
		const details = target.closest("details.session-photos");
		const summary = details?.querySelector(":scope > summary");
		if (focusTarget.kind === "upload") {
			const uploadControl = target.querySelector(
				".photo-upload-input, .photo-upload-submit",
			);
			if (uploadControl) {
				uploadControl.focus();
				return;
			}
			if (summary) {
				summary.focus();
				return;
			}
			target.querySelector(".photo-delete-start")?.focus();
			return;
		}

		const deleteButtons = target.querySelectorAll(".photo-delete-start");
		const nextButton = deleteButtons[
			Math.min(focusTarget.index, deleteButtons.length - 1)
		];
		if (nextButton) {
			nextButton.focus();
			return;
		}
		if (summary) {
			summary.focus();
			return;
		}
		target.querySelector(".photo-upload-input, .photo-upload-submit")?.focus();
	}

	async function reloadFragment(
		source,
		message,
		isError = false,
		focusTarget = { kind: "upload" },
	) {
		const content = source.closest(".session-photos-content");
		const target = source.closest("#session-photos-target");
		const fragmentUrl = content?.dataset.fragmentUrl;
		if (!target || !fragmentUrl) throw new Error("Missing photo fragment target");

		const response = await fetch(fragmentUrl, {
			credentials: "same-origin",
			headers: { "HX-Request": "true" },
		});
		if (!response.ok) throw new Error("Photo fragment request failed");

		// The inserted HTML is generated by the same-origin server and contains no
		// client-provided strings.
		target.innerHTML = await response.text();
		if (window.htmx) window.htmx.process(target);
		enhancePhotoInputs(target);

		const refreshed = target.querySelector(".session-photos-content");
		const details = target.closest("details.session-photos");
		const summary = details?.querySelector(":scope > summary");
		if (summary && refreshed?.dataset.photoCount) {
			summary.textContent = `写真 (${refreshed.dataset.photoCount})`;
		}
		if (refreshed) setStatus(refreshed, message, isError);
		restoreFocus(target, focusTarget);
	}

	function openPhotosFromHash() {
		if (location.hash !== "#photos") return;
		const details = document.querySelector("details.session-photos#photos");
		if (details) details.open = true;
	}

	if (document.readyState === "loading") {
		document.addEventListener(
			"DOMContentLoaded",
			() => {
				openPhotosFromHash();
				enhancePhotoInputs();
			},
			{ once: true },
		);
	} else {
		openPhotosFromHash();
		enhancePhotoInputs();
	}
	document.addEventListener("htmx:afterSwap", (event) => {
		enhancePhotoInputs(event.target);
	});

	document.addEventListener("submit", async (event) => {
		const form = event.target.closest?.(".photo-upload-form");
		if (!form) return;
		event.preventDefault();
		if (isMutationBusy(form)) return;

		const input = form.querySelector(".photo-upload-input");
		const files = Array.from(input?.files || []);
		if (files.length === 0) {
			setStatus(form, "アップロードする写真を選択してください。", true);
			return;
		}

		const currentCount = Number(
			form.closest(".session-photos-content")?.dataset.photoCount || "0",
		);
		if (files.length > MAX_PHOTOS - currentCount) {
			setStatus(
				form,
				`追加できる写真は残り${Math.max(0, MAX_PHOTOS - currentCount)}枚です。`,
				true,
			);
			return;
		}

		setMutationBusy(form, true);
		let successfulCount = 0;
		let activeFile = files[0];
		try {
			for (let index = 0; index < files.length; index += 1) {
				activeFile = files[index];
				setStatus(form, `${index + 1} / ${files.length} 枚をアップロード中…`);
				const body = new FormData();
				body.append("photo", files[index]);
				const response = await fetch(form.action, {
					method: "POST",
					body,
					credentials: "same-origin",
				});
				if (!response.ok) {
					const detail = await responseError(response);
					const message = `${successfulCount}件成功、${index + 1}件目（${activeFile.name}）のアップロードに失敗しました。${detail}`;
					input.value = "";
					if (successfulCount > 0) {
						await reloadFragment(form, message, true);
					} else {
						setStatus(form, message, true);
					}
					return;
				}
				successfulCount += 1;
			}
			input.value = "";
			await reloadFragment(form, `${files.length}枚の写真を追加しました。`);
		} catch (_error) {
			const message =
				successfulCount === files.length
					? `${successfulCount}件のアップロードは成功しましたが、一覧を更新できませんでした。ページを再読み込みしてください。`
					: `${successfulCount}件成功、${successfulCount + 1}件目（${activeFile.name}）のアップロードに失敗しました。通信を確認して再度お試しください。`;
			input.value = "";
			if (successfulCount > 0) {
				try {
					await reloadFragment(
						form,
						successfulCount === files.length
							? `${successfulCount}枚の写真を追加しました。`
							: message,
						successfulCount !== files.length,
					);
				} catch (_reloadError) {
					setStatus(form, message, true);
				}
			} else {
				setStatus(form, message, true);
			}
		} finally {
			setMutationBusy(form, false);
		}
	});

	document.addEventListener("click", async (event) => {
		const start = event.target.closest?.(".photo-delete-start");
		if (start) {
			if (start.disabled || isMutationBusy(start)) return;
			const confirmation = document.getElementById(
				start.getAttribute("aria-controls") || "",
			);
			if (!confirmation) return;
			start.hidden = true;
			start.setAttribute("aria-expanded", "true");
			confirmation.hidden = false;
			confirmation.querySelector(".photo-delete-confirm")?.focus();
			return;
		}

		const cancel = event.target.closest?.(".photo-delete-cancel");
		if (cancel) {
			if (cancel.disabled) return;
			const confirmation = cancel.closest(".photo-delete-confirmation");
			const deleteStart = confirmation
				?.closest(".session-photo-actions")
				?.querySelector(".photo-delete-start");
			confirmation.hidden = true;
			if (deleteStart) {
				deleteStart.hidden = false;
				deleteStart.setAttribute("aria-expanded", "false");
				deleteStart.focus();
			}
			return;
		}

		const confirm = event.target.closest?.(".photo-delete-confirm");
		if (!confirm) return;
		if (confirm.disabled || isMutationBusy(confirm)) return;
		const confirmation = confirm.closest(".photo-delete-confirmation");
		const question = confirmation?.querySelector(".photo-delete-question");
		const items = Array.from(
			confirm
				.closest(".session-photos-content")
				?.querySelectorAll(".session-photo-item") || [],
		);
		const deletedIndex = Math.max(
			0,
			items.indexOf(confirm.closest(".session-photo-item")),
		);
		setMutationBusy(confirm, true);
		if (question) question.textContent = "削除中…";
		setStatus(confirm, "写真を削除中…");
		try {
			const response = await fetch(confirm.dataset.deleteUrl, {
				method: "DELETE",
				credentials: "same-origin",
			});
			if (!response.ok) {
				setStatus(confirm, await responseError(response), true);
				if (question) question.textContent = "削除しますか？";
				return;
			}
			await reloadFragment(confirm, "写真を削除しました。", false, {
				kind: "delete",
				index: deletedIndex,
			});
		} catch (_error) {
			setStatus(confirm, "通信に失敗しました。接続を確認して再度お試しください。", true);
			if (question) question.textContent = "削除しますか？";
		} finally {
			setMutationBusy(confirm, false);
		}
	});
})();
